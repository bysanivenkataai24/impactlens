"""Synthetic *smoke-test* data: abstract shapes on noise, labelled with the class names.

THIS IS NOT VEHICLE DATA. It contains no cars and no damage. It exists so that
the whole pipeline (manifest -> dedup -> group split -> label export ->
training loop -> evaluation -> artifact export -> service adapter) can be
executed end to end on a laptop CPU in about a minute. A model trained on it
has learned to find coloured blobs and nothing else.

The generator deliberately includes the awkward cases the pipeline must handle:
two views per "incident", an exact duplicate, a re-encoded near-duplicate, an
EXIF-rotated photo and negative images.
"""

from __future__ import annotations

import csv
import io
import json
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from ..taxonomy import MODEL_DAMAGE_TYPES

SMOKE_SOURCE = "impactlens-smoke"
SMOKE_LICENSE = "CC0-1.0 (procedurally generated by impactlens.data.synthetic; not vehicle data)"

_COLOURS = {
    "dent": (40, 60, 90),
    "scratch": (235, 235, 240),
    "crack": (20, 20, 20),
    "glass_shatter": (120, 200, 230),
    "lamp_broken": (240, 140, 20),
    "tire_flat": (10, 10, 10),
}


def _shape(
    name: str, cx: float, cy: float, size: float, rng: np.random.Generator
) -> list[tuple[float, float]]:
    """A distinct polygon per class, centred at (cx, cy)."""
    if name == "dent":  # ellipse
        return [
            (cx + size * math.cos(a), cy + 0.6 * size * math.sin(a))
            for a in np.linspace(0, 2 * math.pi, 24, endpoint=False)
        ]
    if name == "scratch":  # long thin slanted bar
        tilt = rng.uniform(-0.4, 0.4)
        return [
            (cx - size * 1.6, cy - 3 + tilt * -size),
            (cx + size * 1.6, cy - 3 + tilt * size),
            (cx + size * 1.6, cy + 3 + tilt * size),
            (cx - size * 1.6, cy + 3 + tilt * -size),
        ]
    if name == "crack":  # zigzag band
        xs = np.linspace(cx - size * 1.3, cx + size * 1.3, 7)
        top = [(x, cy + (8 if i % 2 else -8) - 4) for i, x in enumerate(xs)]
        bottom = [(x, cy + (8 if i % 2 else -8) + 4) for i, x in enumerate(xs)][::-1]
        return top + bottom
    if name == "glass_shatter":  # star
        points = []
        for i in range(16):
            radius = size if i % 2 == 0 else size * 0.45
            angle = i * math.pi / 8
            points.append((cx + radius * math.cos(angle), cy + radius * math.sin(angle)))
        return points
    if name == "lamp_broken":  # rectangle with a notch
        s = size
        return [
            (cx - s, cy - s * 0.6),
            (cx + s, cy - s * 0.6),
            (cx + s, cy + s * 0.6),
            (cx, cy + s * 0.1),
            (cx - s, cy + s * 0.6),
        ]
    if name == "tire_flat":  # half disc
        arc = [
            (cx + size * math.cos(a), cy + size * math.sin(a))
            for a in np.linspace(math.pi, 2 * math.pi, 14)
        ]
        return [*arc, (cx + size, cy + size * 0.25), (cx - size, cy + size * 0.25)]
    raise ValueError(name)


def _scene(rng: np.random.Generator, width: int, height: int, classes: list[str]):
    base = rng.integers(90, 170, size=3)
    pixels = np.clip(rng.normal(base, 12, size=(height, width, 3)), 0, 255).astype(np.uint8)
    image = Image.fromarray(pixels)
    draw = ImageDraw.Draw(image)
    instances = []
    for name in classes:
        size = rng.uniform(18, 34)
        cx = rng.uniform(size * 1.8, width - size * 1.8)
        cy = rng.uniform(size * 1.2, height - size * 1.2)
        polygon = _shape(name, cx, cy, size, rng)
        draw.polygon(polygon, fill=_COLOURS[name])
        instances.append((name, polygon))
    return image, instances


def _jpeg(image: Image.Image, quality: int = 92, exif: Image.Exif | None = None) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, "JPEG", quality=quality, **({"exif": exif} if exif else {}))
    return buffer.getvalue()


def generate_smoke_dataset(root: Path, *, incidents: int = 30, seed: int = 0) -> dict:
    """Write ``raw/images``, ``raw/negatives``, ``raw/annotations.json`` and ``raw/groups.csv``."""
    root = Path(root)
    images_dir = root / "raw" / "images"
    negatives_dir = root / "raw" / "negatives"
    images_dir.mkdir(parents=True, exist_ok=True)
    (negatives_dir / "plain_background").mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)

    coco = {
        "info": {"description": "ImpactLens SMOKE-TEST data. Abstract shapes. Not vehicle data."},
        "licenses": [{"id": 1, "name": SMOKE_LICENSE}],
        "categories": [{"id": i + 1, "name": name} for i, name in enumerate(MODEL_DAMAGE_TYPES)],
        "images": [],
        "annotations": [],
    }
    groups: list[dict] = []
    annotation_id = 1

    def add(file_name: str, data: bytes, size: tuple[int, int], instances, incident: str) -> None:
        nonlocal annotation_id
        (images_dir / file_name).write_bytes(data)
        image_id = len(coco["images"]) + 1
        coco["images"].append(
            {"id": image_id, "file_name": file_name, "width": size[0], "height": size[1]}
        )
        for name, polygon in instances:
            xs, ys = [p[0] for p in polygon], [p[1] for p in polygon]
            coco["annotations"].append(
                {
                    "id": annotation_id,
                    "image_id": image_id,
                    "category_id": MODEL_DAMAGE_TYPES.index(name) + 1,
                    "segmentation": [[round(v, 2) for point in polygon for v in point]],
                    "bbox": [min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)],
                    "area": (max(xs) - min(xs)) * (max(ys) - min(ys)),
                    "iscrowd": 0,
                }
            )
            annotation_id += 1
        groups.append(
            {
                "file_name": file_name,
                "incident_id": incident,
                "vehicle_group_id": f"veh-{incident}",
                "meta_lighting": "synthetic",
            }
        )

    width, height = 320, 256
    for index in range(incidents):
        incident = f"inc-{index:03d}"
        # Every class appears regularly so that even this tiny set covers the taxonomy.
        classes = [
            MODEL_DAMAGE_TYPES[(index + k) % len(MODEL_DAMAGE_TYPES)] for k in range(1 + index % 3)
        ]
        for view in range(2):  # two "views" of one incident: must never be split apart
            image, instances = _scene(rng, width, height, classes)
            add(f"{incident}_view{view}.jpg", _jpeg(image), image.size, instances, incident)

    # Exact duplicate and a re-encoded near-duplicate of the first image.
    first = images_dir / "inc-000_view0.jpg"
    first_instances = [
        (
            MODEL_DAMAGE_TYPES[a["category_id"] - 1],
            list(zip(a["segmentation"][0][0::2], a["segmentation"][0][1::2], strict=True)),
        )
        for a in coco["annotations"]
        if a["image_id"] == 1
    ]
    add(
        "copy_of_inc-000_view0.jpg", first.read_bytes(), (width, height), first_instances, "inc-900"
    )
    with Image.open(first) as original:
        add(
            "reencoded_inc-000_view0.jpg",
            _jpeg(original, quality=70),
            (width, height),
            first_instances,
            "inc-901",
        )

    # A portrait photo stored rotated with EXIF orientation 6, annotated in display space.
    portrait, portrait_instances = _scene(rng, 256, 320, ["dent", "scratch"])
    exif = Image.Exif()
    exif[0x0112] = 6
    stored = portrait.transpose(Image.Transpose.ROTATE_90)  # what a phone sensor would store
    add(
        "portrait_exif6.jpg", _jpeg(stored, exif=exif), portrait.size, portrait_instances, "inc-902"
    )

    for index in range(8):
        base = rng.integers(90, 170, size=3)
        pixels = np.clip(rng.normal(base, 12, size=(height, width, 3)), 0, 255).astype(np.uint8)
        (negatives_dir / "plain_background" / f"neg_{index:02d}.jpg").write_bytes(
            _jpeg(Image.fromarray(pixels))
        )

    (root / "raw" / "annotations.json").write_text(json.dumps(coco), encoding="utf-8")
    with (root / "raw" / "groups.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=["file_name", "incident_id", "vehicle_group_id", "meta_lighting"]
        )
        writer.writeheader()
        writer.writerows(groups)
    return {"images": len(coco["images"]), "annotations": len(coco["annotations"]), "negatives": 8}
